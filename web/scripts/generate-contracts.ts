export const GENERATED_HEADER = "Code generated by generate-contracts.ts; DO NOT EDIT.";

export interface AdminErrorCodeDefinition {
	code: number;
	name: string;
	reason: string;
}

export type HostOperationStatus = "available" | "unavailable" | "absent";

export const HOST_OPERATION_STATUSES: readonly HostOperationStatus[] = [
	"available",
	"unavailable",
	"absent",
];

export interface HostOperationDefinition {
	name: string;
	status: HostOperationStatus;
	reason?: string;
}

export interface NativeRoutes {
	controller: string[];
	workspace: string[];
}

export interface OwnershipDefinition {
	method: string;
	fc: string;
	owner: string;
	profile: string;
	route: string;
	status?: HostOperationStatus;
	reason?: string;
}

export interface MethodFieldSchema {
	name: string;
	type: string;
	optional?: boolean;
}

export interface MethodSchema {
	name: string;
	params: MethodFieldSchema[];
	result: MethodFieldSchema[];
}

export interface ProtocolCatalog {
	schemaVersion: number;
	operations: {
		host: HostOperationDefinition[];
		controller: string[];
	};
	nativeRoutes: NativeRoutes;
	ownership: OwnershipDefinition[];
	methodSchemas: {
		host: MethodSchema[];
		controller: MethodSchema[];
	};
	thinkingLevels: string[];
	promptContentBlockTypes: string[];
	adminErrorCodes: AdminErrorCodeDefinition[];
}

