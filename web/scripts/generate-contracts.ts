const OWNER_SET = new Set<string>(OWNERS);
export const METHOD_FIELD_TYPES = ["string", "number", "boolean", "object", "array"] as const;
const METHOD_FIELD_TYPE_SET = new Set<string>(METHOD_FIELD_TYPES);

